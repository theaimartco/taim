//! Design tokens as a compiled artifact (Pillar XIV).
//!
//! Compiles high-level design tokens, physical luminance specifications (Pillar II),
//! and physical material parameters (Pillar III) into zero-overhead static Rust constants.
//! Eliminates runtime theme resolution overhead and verifies bitwise token immutability.

use crate::theme::Theme;
use crate::tokens::{ColorTokens, LuminanceTokens, Scheme};
use taim_core::Color;

/// A statically compiled palette and lighting specification.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CompiledPalette {
    /// Palette scheme (Light, Dark, HighContrast).
    pub scheme: Scheme,
    /// Background color in linear RGBA floats.
    pub background: [f32; 4],
    /// Surface card/panel color in linear RGBA floats.
    pub surface: [f32; 4],
    /// Primary accent color in linear RGBA floats.
    pub primary: [f32; 4],
    /// Content on primary color in linear RGBA floats.
    pub on_primary: [f32; 4],
    /// Content on surface color in linear RGBA floats.
    pub on_surface: [f32; 4],
    /// Semantic error color in linear RGBA floats.
    pub error: [f32; 4],
    /// Keyboard/input focus ring color in linear RGBA floats.
    pub focus: [f32; 4],
    /// Diffuse surface luminance in candelas per square metre (nits).
    pub surface_nits: f32,
    /// Selected/emphasized element luminance in nits.
    pub emphasis_nits: f32,
    /// Active highlight/accent luminance in nits.
    pub highlight_nits: f32,
    /// Peak panel HDR emission ceiling in nits.
    pub peak_nits: f32,
    /// Floating pane microfacet roughness.
    pub overlay_roughness: f32,
    /// Floating pane light transmission fraction (0..1).
    pub overlay_transmission: f32,
    /// Floating pane refractive index (e.g. 1.52 for soda-lime glass).
    pub overlay_ior: f32,
    /// Physical pane thickness in millimetres.
    pub overlay_thickness_mm: f32,
    /// Chromatic dispersion delta between spectral ends.
    pub overlay_dispersion: f32,
}

impl CompiledPalette {
    /// Compiles a runtime [`Theme`] and [`LuminanceTokens`] into a static specification.
    pub fn compile(theme: &Theme, luminance: LuminanceTokens) -> Self {
        let colors = theme.colors();
        let materials = theme.materials();
        let overlay = materials.overlay;

        Self {
            scheme: theme.scheme(),
            background: color_to_rgba(colors.background),
            surface: color_to_rgba(colors.surface),
            primary: color_to_rgba(colors.primary),
            on_primary: color_to_rgba(colors.on_primary),
            on_surface: color_to_rgba(colors.on_surface),
            error: color_to_rgba(colors.error),
            focus: color_to_rgba(colors.focus),
            surface_nits: luminance.surface,
            emphasis_nits: luminance.emphasis,
            highlight_nits: luminance.highlight,
            peak_nits: luminance.peak,
            overlay_roughness: overlay.roughness,
            overlay_transmission: overlay.transmission,
            overlay_ior: overlay.ior,
            overlay_thickness_mm: overlay.thickness_mm,
            overlay_dispersion: overlay.dispersion,
        }
    }

    /// Reconstructs runtime [`ColorTokens`] from this compiled palette.
    pub fn to_color_tokens(&self) -> ColorTokens {
        ColorTokens {
            background: rgba_to_color(self.background),
            surface: rgba_to_color(self.surface),
            primary: rgba_to_color(self.primary),
            on_primary: rgba_to_color(self.on_primary),
            on_surface: rgba_to_color(self.on_surface),
            on_surface_variant: rgba_to_color(self.on_surface),
            error: rgba_to_color(self.error),
            focus: rgba_to_color(self.focus),
        }
    }
}

/// Helper converting a [`Color`] into an `[r, g, b, a]` float array.
#[inline]
const fn color_to_rgba(c: Color) -> [f32; 4] {
    [c.r, c.g, c.b, c.a]
}

/// Helper converting an `[r, g, b, a]` float array back into a [`Color`].
#[inline]
const fn rgba_to_color(rgba: [f32; 4]) -> Color {
    Color {
        r: rgba[0],
        g: rgba[1],
        b: rgba[2],
        a: rgba[3],
    }
}

/// Token compiler that emits static Rust code constants from runtime tokens.
pub struct TokenCompiler;

impl TokenCompiler {
    /// Compiles a [`Theme`] and [`LuminanceTokens`] into formatted static Rust constant code.
    pub fn emit_rust_source(const_name: &str, theme: &Theme, luminance: LuminanceTokens) -> String {
        let compiled = CompiledPalette::compile(theme, luminance);
        format!(
            r#"// Generated by taim-design TokenCompiler (Pillar XIV). Do not edit manually.
use taim_design::compiler::CompiledPalette;
use taim_design::tokens::Scheme;

pub const {name}: CompiledPalette = CompiledPalette {{
    scheme: Scheme::{scheme:?},
    background: [{bg0:.4}, {bg1:.4}, {bg2:.4}, {bg3:.4}],
    surface: [{sf0:.4}, {sf1:.4}, {sf2:.4}, {sf3:.4}],
    primary: [{pr0:.4}, {pr1:.4}, {pr2:.4}, {pr3:.4}],
    on_primary: [{op0:.4}, {op1:.4}, {op2:.4}, {op3:.4}],
    on_surface: [{os0:.4}, {os1:.4}, {os2:.4}, {os3:.4}],
    error: [{er0:.4}, {er1:.4}, {er2:.4}, {er3:.4}],
    focus: [{fc0:.4}, {fc1:.4}, {fc2:.4}, {fc3:.4}],
    surface_nits: {s_nits:.1},
    emphasis_nits: {e_nits:.1},
    highlight_nits: {h_nits:.1},
    peak_nits: {p_nits:.1},
    overlay_roughness: {rough:.3},
    overlay_transmission: {trans:.3},
    overlay_ior: {ior:.3},
    overlay_thickness_mm: {thick:.3},
    overlay_dispersion: {disp:.3},
}};
"#,
            name = const_name,
            scheme = compiled.scheme,
            bg0 = compiled.background[0],
            bg1 = compiled.background[1],
            bg2 = compiled.background[2],
            bg3 = compiled.background[3],
            sf0 = compiled.surface[0],
            sf1 = compiled.surface[1],
            sf2 = compiled.surface[2],
            sf3 = compiled.surface[3],
            pr0 = compiled.primary[0],
            pr1 = compiled.primary[1],
            pr2 = compiled.primary[2],
            pr3 = compiled.primary[3],
            op0 = compiled.on_primary[0],
            op1 = compiled.on_primary[1],
            op2 = compiled.on_primary[2],
            op3 = compiled.on_primary[3],
            os0 = compiled.on_surface[0],
            os1 = compiled.on_surface[1],
            os2 = compiled.on_surface[2],
            os3 = compiled.on_surface[3],
            er0 = compiled.error[0],
            er1 = compiled.error[1],
            er2 = compiled.error[2],
            er3 = compiled.error[3],
            fc0 = compiled.focus[0],
            fc1 = compiled.focus[1],
            fc2 = compiled.focus[2],
            fc3 = compiled.focus[3],
            s_nits = compiled.surface_nits,
            e_nits = compiled.emphasis_nits,
            h_nits = compiled.highlight_nits,
            p_nits = compiled.peak_nits,
            rough = compiled.overlay_roughness,
            trans = compiled.overlay_transmission,
            ior = compiled.overlay_ior,
            thick = compiled.overlay_thickness_mm,
            disp = compiled.overlay_dispersion,
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compiles_theme_into_static_palette_with_exact_color_fidelity() {
        let theme = Theme::new(Scheme::Dark);
        let palette = CompiledPalette::compile(&theme, LuminanceTokens::HDR);

        assert_eq!(palette.scheme, Scheme::Dark);
        assert_eq!(palette.surface_nits, 203.0);
        assert_eq!(palette.emphasis_nits, 400.0);
        assert_eq!(palette.highlight_nits, 1000.0);
        assert_eq!(palette.peak_nits, 1600.0);

        // Verify roundtrip fidelity
        let reconstructed = palette.to_color_tokens();
        assert_eq!(reconstructed.primary, theme.colors().primary);
        assert_eq!(reconstructed.surface, theme.colors().surface);
    }

    #[test]
    fn emits_syntactically_valid_rust_code() {
        let theme = Theme::new(Scheme::Light);
        let source =
            TokenCompiler::emit_rust_source("LIGHT_PALETTE", &theme, LuminanceTokens::STANDARD);

        assert!(source.contains("pub const LIGHT_PALETTE: CompiledPalette = CompiledPalette {"));
        assert!(source.contains("scheme: Scheme::Light"));
        assert!(source.contains("surface_nits: 203.0"));
    }
}
